// Array.protocol.includes: checks whether an array contains a certain element
console.log([1, 2, 3].includes(2))  // true

// String.prototype.startsWith: determines if a string starts with specified character
console.log("Hello".startsWith("He"));  // true

// String.prototype.endsWith: determines if a string ends with specified characters
console.log("Hello".endsWith("lo"));    // true